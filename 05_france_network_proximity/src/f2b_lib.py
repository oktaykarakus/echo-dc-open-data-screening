"""F2-B library: frozen arms (F2-A protocol), AUC, fixed-budget metrics, paired spatial-block bootstrap, decision rule.
Pure numpy/pandas/scipy; no I/O except load_arms(). No scoring logic is duplicated: B0-QA normalised columns and the equal-weight
score come from stage 01's saved scores_B0QA.csv (generated by stage 01 scoring.py)."""
import math, os
import numpy as np, pandas as pd
from scipy.stats import rankdata

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
MASTER = os.path.join(ROOT, "data", "inputs", "inventory_indicator_master_87col.csv")
SCORES = os.path.join(ROOT, "01_baseline_scoring", "results", "scores_B0QA.csv")
EPS = 1e-6
ARMS = ["A", "P", "H", "B*", "C"]          # five confirmatory arms
DESCR = ["Opportunity", "Feasibility"]     # descriptive components of A
FRACS = (0.10, 0.20)


def pareto_layers(V):
    """Non-dominated sorting (maximisation). a dominates b if a>=b on all columns and a>b on at least one.
    Identical vectors never dominate each other and share a layer. Exact float comparison. Returns layer index 1,2,..."""
    V = np.asarray(V, dtype=float)
    layer = np.zeros(len(V), dtype=int)
    remaining = np.arange(len(V))
    L = 0
    while remaining.size:
        L += 1
        R = V[remaining]
        ge = (R[None, :, :] >= R[:, None, :]).all(axis=2)   # ge[i, j]: j >= i on every dimension
        gt = (R[None, :, :] > R[:, None, :]).any(axis=2)    # gt[i, j]: j > i on some dimension
        dominated = (ge & gt).any(axis=1)
        layer[remaining[~dominated]] = L
        remaining = remaining[dominated]
    return layer


def strict_position(values_desc):
    """Strict total order: descending value, ties broken by row order (stage 01 rule). Returns position 0..n-1 (0 = best)."""
    n = len(values_desc)
    order = np.lexsort((np.arange(n), -np.asarray(values_desc, float)))
    pos = np.empty(n, dtype=int)
    pos[order] = np.arange(n)
    return pos


def load_arms():
    """All arms on the full 1,216-record inventory (global normalisation as in V1). Returns (df, vals, pos):
    vals[arm] = value (higher = better) used for AUC; pos[arm] = strict rank position (0 = best) used for top-k."""
    s = pd.read_csv(SCORES)
    m = pd.read_csv(MASTER, usecols=["facility_id", "pop_density_2p5km", "hotmaps_heat_sum_2p5km"])
    assert len(s) == len(m) == 1216 and (s.facility_id.values == m.facility_id.values).all()
    n = len(s)
    heat, pop, hdd = s.norm_heat_sum_2p5km, s.norm_pop_density_2p5km, s.norm_hdd_2024
    D = (heat + hdd + pop) / 3.0
    S = (s.norm_anchor_count_2p5km + s.norm_anchor_diversity_2p5km + s.norm_nearest_anchor_distance_m) / 3.0
    F = s.norm_urban_compactness_2p5km
    bstar = ((D + EPS) * (S + EPS) * (F + EPS)) ** (1.0 / 3.0)
    layer = pareto_layers(np.column_stack([D, S, F]))
    vals = {"A": s.echo_dc_score_raw_equal.values, "P": m.pop_density_2p5km.values, "H": m.hotmaps_heat_sum_2p5km.values,
            "B*": bstar.values, "Opportunity": s.opportunity_score_equal.values, "Feasibility": s.feasibility_score_equal.values}
    pos = {k: strict_position(v) for k, v in vals.items()}
    # C: layer ascending, then B* descending, then row order
    order = np.lexsort((np.arange(n), -bstar.values, layer))
    pc = np.empty(n, dtype=int); pc[order] = np.arange(n)
    pos["C"] = pc
    vals["C"] = -pc.astype(float)
    df = pd.DataFrame({"facility_id": s.facility_id, "D": D, "S": S, "F": F, "bstar": bstar, "pareto_layer": layer,
                       "road_density": s.major_road_density_2p5km_km_per_km2, "road_dist": s.nearest_major_road_distance_m})
    return df, vals, pos


def auc(y, v):
    """Mann-Whitney AUC with ties = 0.5 (average ranks)."""
    y = np.asarray(y).astype(bool)
    n1, n0 = int(y.sum()), int((~y).sum())
    r = rankdata(v)
    return (r[y].sum() - n1 * (n1 + 1) / 2.0) / (n1 * n0)


def topk_metrics(y, key, idx, frac):
    """Fixed-budget metrics on records idx (duplicates allowed). key: strict position (lower = better). k = ceil(frac * len(idx)).
    Ties (equal key, e.g. duplicated resampled records) keep idx order (stable)."""
    idx = np.asarray(idx)
    N = len(idx); k = int(math.ceil(frac * N))
    order = idx[np.argsort(key[idx], kind="stable")]
    tp = int(y[order[:k]].sum()); npos = int(y[idx].sum()); prev = npos / N
    prec = tp / k
    return {"k": k, "tp": tp, "precision": prec, "recall": tp / npos if npos else np.nan, "enrichment": prec / prev if prev else np.nan}


def metric_vector(y, vals, pos, idx, arms):
    """All metrics for one sample (full sample or one bootstrap replicate)."""
    out = {}
    yy, vv = y[idx], {a: vals[a][idx] for a in arms}
    for a in arms:
        out[f"auc|{a}"] = auc(yy, vv[a])
    for a in arms:
        if a != "P":
            out[f"dauc|{a}"] = out[f"auc|{a}"] - out["auc|P"]
    for f in FRACS:
        tag = f"{int(f * 100)}"
        mm = {a: topk_metrics(y, pos[a], idx, f) for a in arms}
        for a in arms:
            for q in ("tp", "precision", "recall", "enrichment"):
                out[f"{q}@{tag}|{a}"] = mm[a][q]
        for a in arms:
            if a != "P":
                out[f"dprecision@{tag}|{a}"] = mm[a]["precision"] - mm["P"]["precision"]
                out[f"dtp@{tag}|{a}"] = mm[a]["tp"] - mm["P"]["tp"]
    return out


def draw(groups, rng):
    """One paired block resample: draw G blocks with replacement; every record of a drawn block enters together."""
    pick = rng.integers(0, len(groups), size=len(groups))
    return np.concatenate([groups[g] for g in pick])


def block_bootstrap(y, vals, pos, blocks, arms, reps, seed, level=0.90, record_level=False):
    """Paired block bootstrap. blocks: array of block labels per record (records of one block are resampled together;
    campus records must already share the block label). record_level=True resamples single records (independence benchmark only).
    Returns (point dict, ci dict {metric: (lo, hi)}, info). No replicate history is stored."""
    n = len(y)
    allidx = np.arange(n)
    point = metric_vector(y, vals, pos, allidx, arms)
    if record_level:
        groups = [np.array([i]) for i in range(n)]
    else:
        lab = pd.Series(blocks)
        groups = [g.values for _, g in pd.Series(allidx).groupby(lab.values)]
    G = len(groups)
    rng = np.random.default_rng(seed)
    acc = {k: [] for k in point}
    skipped = 0
    for _ in range(reps):
        idx = draw(groups, rng)
        yy = y[idx]
        if yy.sum() == 0 or yy.sum() == len(yy):
            skipped += 1; continue
        mv = metric_vector(y, vals, pos, idx, arms)
        for k, v in mv.items():
            acc[k].append(v)
    a = (1 - level) / 2
    ci = {k: (float(np.nanquantile(v, a)), float(np.nanquantile(v, 1 - a))) for k, v in acc.items()}
    sd = {k: float(np.nanstd(v, ddof=1)) for k, v in acc.items()}
    return point, ci, {"groups": G, "reps": reps, "skipped": skipped, "sd": sd, "seed": seed}


def decide(g_ok, d_point, d_ci, auc_a, auc_p, hw, g4_ok, prec_ok, sens_pos, sens_any_ci_below0):
    """Frozen F2-A decision table, first match applies."""
    if not g_ok:
        return "Criterion failure"
    if d_ci[1] < 0:
        return "No demonstrated support (inferior)"
    if hw > 0.06 or not g4_ok:
        return "No demonstrated support (uncertainty prevents interpretation)"
    if auc_a <= 0.55 and auc_p <= 0.55:
        return "No demonstrated support (criterion uninformative about urban context)"
    if d_point >= 0.03 and d_ci[0] > 0 and prec_ok and sens_pos and not sens_any_ci_below0:
        return "Strong support"
    return "Limited support"


def partial_spearman(y, x, controls):
    """Partial Spearman correlation of x with y given controls (columns), via rank residuals."""
    R = lambda a: rankdata(a)
    C = np.column_stack([np.ones(len(y))] + [R(c) for c in controls])
    res = lambda t: R(t) - C @ np.linalg.lstsq(C, R(t), rcond=None)[0]
    ry, rx = res(y), res(x)
    return float(np.corrcoef(ry, rx)[0, 1])
